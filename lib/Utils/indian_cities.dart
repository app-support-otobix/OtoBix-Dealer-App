  static String? stateOf(String city) {
    final c = city.trim().toLowerCase();
    String? found;
    for (final e in _byState.entries) {
      if (e.value.any((x) => x.toLowerCase() == c)) {
        if (found != null) return null;
        found = e.key;
      }
    }
    return found;
